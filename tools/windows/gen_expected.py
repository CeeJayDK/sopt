#!/usr/bin/env python3
"""Writes tools/windows/expected.hpp: what other cards of the same family measure in each OpBench test (owner,
2026-10-06: OpBench tells the user when their card differs from its family, so such reports get noticed).

    gen_expected.py            (rerun when reports are added to docs/opbench)

Families are the cost models (tools/site/build.py MODEL_RULES, the card name; NAME_BY_DEVICE for generic names).
Expected value per test = the median over the family's cards of the throughput cost (units_vs_base), one report
per card (its newest), only clean reports (neg ~0) and readings with consensus. Only hardware is stored.
"""
import csv
import importlib.util
import json
import os
import re
import statistics
import sys

sys.dont_write_bytecode = True  # importing tools/site/build.py would leave a __pycache__ in the repo

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
spec = importlib.util.spec_from_file_location("site_build", os.path.join(ROOT, "tools", "site", "build.py"))
site = importlib.util.module_from_spec(spec)
spec.loader.exec_module(site)

UNRELIABLE = site.UNRELIABLE  # reports whose clock moved during the run: left out (tools/site/build.py)


# Free steps whose readings swing by several units on clean runs (noise, not the card).
NOISY = {"transpose"}


def version_key(info, base):
    v = tuple(int(x) for x in info.get("version", "0.0").split(".") if x.isdigit())
    m = re.search(r"-v(\d+)", base)
    return (v, int(m.group(1)) if m else 0)


def rows_of(path):
    with open(path, encoding="utf-8", errors="replace") as f:
        lines = [l for l in f.read().splitlines() if l and not l.startswith("#")]
    return list(csv.DictReader(lines))


def main():
    arch = json.load(open(os.path.join(ROOT, "tools", "site", "architectures.json")))
    labels = {}
    for v in arch["vendors"]:
        for a in v["architectures"]:
            if a["model"]:
                labels.setdefault(a["model"], []).append(a["name"])
    cards = {}  # (name, stage) -> (key, model, rows)
    reports = [("opbench", p) for p in sorted(os.listdir(os.path.join(ROOT, "docs", "opbench")))]
    if os.path.isdir(os.path.join(ROOT, "docs", "stagebench")):
        reports += [("stagebench", p) for p in sorted(os.listdir(os.path.join(ROOT, "docs", "stagebench")))]
    for folder, path in reports:
        if not path.endswith(".csv") or path in UNRELIABLE:
            continue
        full = os.path.join(ROOT, "docs", folder, path)
        info = site.read_report(full)
        stage = info.get("stage", "cs") if folder == "stagebench" else "cs"
        # StageBench before 0.7.9: the vertex run's integer tests were folded away (all 0).
        if stage == "vs" and version_key(info, "")[0] < (0, 7, 9):
            continue
        if info.get("device") in site.SKIP_DEVICES:
            continue
        name = site.clean_name(site.NAME_BY_FILE.get(path) or site.NAME_BY_DEVICE.get(info.get("device", "")) or info.get("gpu", ""))
        model = site.model_of(name)
        if not model:
            continue
        rows = [r for r in rows_of(full) if r.get("config") == "tput" and site.reading_valid(info.get("version", "0"), r["test"])]
        neg = [float(r["units_vs_base"]) for r in rows if r["test"] == "neg"]
        if not neg or abs(neg[0]) > 0.3:
            continue
        cards.setdefault((name, stage), []).append((version_key(info, path[:-4]), model, rows, info))
    # Per card and stage each test from the cleanest run of the newest report's driver (site.by_cleanest: later wins).
    merged = {}
    for k, v in cards.items():
        rows = {}
        for c in site.by_cleanest(v, lambda c: c[0], lambda c: c[3]):
            rows.update((r["test"], r) for r in c[2])
        top = max(v, key=lambda c: c[0])
        merged[k] = (top[0], top[1], list(rows.values()))
    cards = merged
    families = {}
    for (name, stage), (key, model, rows) in sorted(cards.items()):
        fam = families.setdefault((model, stage), {"cards": [], "values": {}})
        fam["cards"].append(name)
        for r in rows:
            # Test names go into C++ string literals: anything but plain names (from an uploaded report) is skipped.
            if r.get("consensus", "yes") == "no" or r["test"] in NOISY or not re.fullmatch(r"[\w.+-]+", r["test"]):
                continue
            try:
                fam["values"].setdefault(r["test"], []).append(float(r["units_vs_base"]))
            except ValueError:
                pass
    out = [
        "// Generated by tools/windows/gen_expected.py from docs/opbench: do not edit, rerun it when reports are added.",
        "// What cards of each family (cost model) measure in the OpBench throughput tests: the median cost over the",
        "// family's cards (one report each). Only hardware, no names of the people who ran them.",
        "#pragma once",
        "",
        "#include <cstring>",
        "#include <regex>",
        "#include <string>",
        "",
        "namespace expected {",
        "",
        "struct Family {",
        "  const char* model;",
        "  const char* label;  // architectures",
        "  int cards;",
        "  const char* stage;  // cs (OpBench), ps / vs (StageBench)",
        "  const char* costs;  // \"test cost test cost ...\"",
        "};",
        "",
        "inline const Family kFamilies[] = {",
    ]
    for model, stage in sorted(families):
        fam = families[(model, stage)]
        costs = " ".join(f"{t} {statistics.median(v):.1f}" for t, v in sorted(fam["values"].items()))
        label = " / ".join(labels.get(model, [model]))
        out.append(f'    {{"{model}", "{label}", {len(fam["cards"])}, "{stage}",')
        # Split long strings into several literals.
        parts = []
        cur = ""
        for tok in re.findall(r"\S+ \S+", costs):
            if len(cur) + len(tok) > 100:
                parts.append(cur)
                cur = ""
            cur += tok + " "
        parts.append(cur)
        for i, p in enumerate(parts):
            out.append(f'     "{p}"' + ("}," if i == len(parts) - 1 else ""))
    out += [
        "};",
        "",
        "// Card name (without (R) / (TM)) -> family, first match wins (ECMAScript regex search).",
        "struct Rule {",
        "  const char* pattern;",
        "  const char* model;",
        "};",
        "inline const Rule kRules[] = {",
    ]
    for pattern, model in site.MODEL_RULES:
        out.append(f'    {{R"({pattern})", "{model}"}},')
    out += ["};", "", "// Generic names that only the device ID tells apart.", "struct Device {", "  unsigned id;",
            "  const char* model;", "};", "inline const Device kDevices[] = {"]
    for dev, name in sorted(site.NAME_BY_DEVICE.items()):
        model = site.model_of(site.clean_name(name))
        if model:
            out.append(f'    {{{dev}, "{model}"}},')
    # How long each program takes on a family's cards (owner, 2026-10-20: shown at the start and in the menu): the median
    # over its cards of each card's median run time (tools/site/build.py run_times: reports with the current tests).
    times = {}
    for name, t in site.run_times().items():
        model = site.model_of(name)
        for tool, secs in t.items():
            if model:
                times.setdefault((model, tool), []).append(secs)
    out += ["};", "", "// Median run time in seconds of each program on the family's cards (StageBench: pixel and vertex runs).",
            "struct RunTime {", "  const char* model;", "  const char* tool;", "  int seconds;", "  int cards;", "};",
            "inline const RunTime kRunTimes[] = {"]
    for (model, tool), v in sorted(times.items()):
        out.append(f'    {{"{model}", "{tool}", {round(statistics.median(v))}, {len(v)}}},')
    out += ["};", "",
            "// The family (cost model) of a card: by device ID, else by name (without (R) / (TM)); nullptr if none yet.",
            "inline const char* modelOf(std::string name, unsigned deviceId) {",
            "  for (const Device& d : kDevices)",
            "    if (d.id == deviceId) return d.model;",
            r'  name = std::regex_replace(name, std::regex(R"(\((R|TM)\))"), "");',
            r'  name = std::regex_replace(name, std::regex(R"(\s+)"), " ");',
            "  for (const Rule& r : kRules)",
            "    if (std::regex_search(name, std::regex(r.pattern))) return r.model;",
            "  return nullptr;",
            "}",
            "",
            "// The family's run time of a program, or nullptr.",
            "inline const RunTime* runTime(const char* model, const char* tool) {",
            "  for (const RunTime& t : kRunTimes)",
            "    if (model && std::strcmp(t.model, model) == 0 && std::strcmp(t.tool, tool) == 0) return &t;",
            "  return nullptr;",
            "}",
            "",
            "}  // namespace expected", ""]
    dst = os.path.join(ROOT, "tools", "windows", "expected.hpp")
    with open(dst, "w", newline="\n") as f:
        f.write("\n".join(out))
    for model in sorted(families):
        print(model, len(families[model]["cards"]), ", ".join(families[model]["cards"]))


if __name__ == "__main__":
    main()
